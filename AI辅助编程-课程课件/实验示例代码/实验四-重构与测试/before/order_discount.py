# -*- coding: utf-8 -*-
"""
实验四 · 重构【前】—— 含“代码坏味道”的样例

请勿直接采纳，这是用于练习“识别坏味道 + AI 辅助重构”的反面教材。

坏味道清单（请在重构前先把它们一一找出来）：
  1) 魔法数字：1 / 2 / 3 / 0.9 / 0.8 / 1000 / 0.95 含义不清；
  2) 重复代码：每个分支结构雷同；
  3) 过长函数 + 深层嵌套：可读性差、难扩展；
  4) 命名不清：calc / o / t 难以理解。

业务规则：
  - 订单按会员类型计价：普通(1) 原价，会员(2) 9 折，VIP(3) 8 折；
  - 单笔合计超过 1000，再整体打 95 折。
"""


def calc(orders):
    t = 0
    for o in orders:
        if o['type'] == 1:
            t = t + o['price'] * 1
        elif o['type'] == 2:
            t = t + o['price'] * 0.9
        elif o['type'] == 3:
            t = t + o['price'] * 0.8
        else:
            t = t + o['price'] * 1
    if t > 1000:
        t = t * 0.95
    return t
